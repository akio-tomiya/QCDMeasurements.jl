# Run this script with QCDMeasurements commit 5576729 in the active environment,
# Julia 1.11.8, Gaugefields 1.1.11, LatticeMatrices 1.2.8, JACC 1.4.0/threads,
# JULIA_NUM_THREADS=4, OPENBLAS_NUM_THREADS=1 (scalar reduction order matters).
# The source check prevents accidentally regenerating the reference with the
# implementation being tested. The optional argument selects the output file.
using JACC
JACC.@init_backend
using QCDMeasurements, SHA, TOML
@assert Threads.nthreads() == 4 "Use JULIA_NUM_THREADS=4 to reproduce scalar reductions"

source = joinpath(pkgdir(QCDMeasurements), "src", "measurements", "measure_topological_charge.jl")
@assert bytes2hex(sha256(read(source))) ==
    "f2390d7f2628cfb096bee4d1dc6d1ab71eab513d72ec1e870264c6b072ba15c0"
include(joinpath(@__DIR__, "..", "gauge_density_helpers.jl"))

L = (3, 4, 5, 6)
positions = [[1,1,1,1], [3,4,5,6], [2,1,3,4], [1,2,4,3], [3,3,1,5], [2,4,2,6]]
fixture = Dict{String,Any}(
    "baseline_commit" => "5576729f81c07955df01bee1f13d1ae12017f2e1",
    "julia_version" => string(VERSION),
    "gaugefields_version" => string(pkgversion(Gaugefields)),
    "latticematrices_version" => "1.2.8",
    "jacc_version" => string(pkgversion(JACC)),
    "lattice" => collect(L), "positions" => positions, "cases" => Dict{String,Any}(),
)
for (backend, colors, label) in ((LatticeMatricesBackend(), 3, "lm_su3"),
                                (LegacyBackend(), 3, "legacy_su3"),
                                (LatticeMatricesBackend(), 2, "lm_su2"))
    U = density_test_field(L; backend, colors)
    charges = get_value(measure(TopologicalChargeMeasurement(U;
        TC_methods=["plaquette", "clover"], improved_topological_charge_definition="both"), U))
    history = get_value(measure(GradientFlowScaleMeasurement(U;
        number_of_flow_steps=0, measure_topological_charge=false), U))
    local_measurement = TopologicalChargeDensityCorrelationMeasurement(U)
    q = Dict(method => [density_point_reference(U, collect(Tuple(site)), method, local_measurement)
        for site in CartesianIndices(L)] for (method, _) in DENSITY_METHOD_KEYS)
    e = Dict(method => [action_point_reference(U, collect(Tuple(site)), method, local_measurement)
        for site in CartesianIndices(L)] for method in ("plaquette", "clover"))
    fixture["cases"][label] = Dict(
        "input_sha256" => bytes2hex(sha256(reinterpret(UInt8, vec(density_test_snapshot(U))))),
        "charges" => charges,
        "actions" => Dict(k => v[1] for (k,v) in history.energy_density),
        "legacy_energy" => get_value(measure(EnergyDensityMeasurement(U), U)),
        "topological_fields" => Dict(k => vec(v) for (k,v) in q),
        "action_fields" => Dict(k => vec(v) for (k,v) in e),
        "topological_sites" => Dict(k => [v[p...] for p in positions] for (k,v) in q),
        "action_sites" => Dict(k => [v[p...] for p in positions] for (k,v) in e),
    )
end
output = isempty(ARGS) ? joinpath(@__DIR__, "gauge_density_v1.toml") : only(ARGS)
open(output, "w") do io
    println(io, "# Values generated by QCDMeasurements before the density API changes.")
    println(io, "# Each field is flattened in Julia column-major (X,Y,Z,T) order.")
    TOML.print(io, fixture; sorted=true)
end
